import { writeFileSync } from 'node:fs';
import * as k from '../vendor/anatomy/iso-kit.mjs';
import * as A from '../vendor/anatomy/audit.mjs';
import { glCamera } from '../vendor/anatomy/gl.mjs';
import { scenes } from './instrument-scenes.mjs';

// Physical concepts and parts lists precede geometry in docs/distinct-instruments.md.
for (const [id, scene] of Object.entries(scenes)) {
  const width = 800,
    height = 500;
  const P = k.fitProjection(k.boxCorners(scene.bounds, -12, scene.top), width, height, {
    pad: 42,
    azimuth: scene.azimuth ?? 42,
    elevation: scene.elevation ?? 29,
  });
  const R = A.recorder(P);
  const at = (p) => k.iso(p, P);
  const line = (d, tone = 'lo', free = false) => k.lineSvg(d, { tone, free });
  const plan = (x, y, w, d, r = 1) => ({ x, y, w, d, r });
  function box(name, x, y, w, d, z, h, opts = {}) {
    const p = plan(x, y, w, d, opts.r ?? 1);
    const shape = R.solid(A.slab(p, z, h, { name, ground: name.startsWith('foot') }, 8));
    const item = R.put({
      name,
      module: opts.module ?? 'base',
      field: opts.field ?? -1,
      driver: opts.driver ?? 'position',
      at: [x + w / 2, y + d / 2, z + h / 2],
      move: opts.move ?? [0, 0, 0],
      shapes: [shape],
      svg: k.solidSvg(k.slabOf(p, z, h, P, 8, Math.min(0.4, h / 4)), { tone: opts.tone ?? 'mid' }),
    });
    if (opts.panel && w > 9 && d > 9) {
      item.svg += line(k.planOutline(k.insetPlan(p, 2), z + h, P, 8));
      for (const [sx, sy] of k.corners(p, 3)) item.svg += line(k.ring(sx, sy, 0.8, z + h, P, 12));
    }
    if (opts.window)
      item.svg += `<g data-window="${opts.window}">${line(k.planOutline(k.insetPlan(p, 3), z + h, P, 8), 'hi')}</g>`;
    if (opts.fader !== undefined) item.svg = `<g data-fader="${opts.fader}">${item.svg}</g>`;
    return item;
  }
  function base(x, y, w, d, h = 7) {
    for (const [i, [fx, fy]] of k.corners(plan(x, y, w, d), 10).entries())
      box(`foot-${i}`, fx - 5, fy - 5, 10, 10, -12, 5, { r: 2 });
    box('chassis', x, y, w, d, -7, h, { r: 5, panel: true });
    for (const [i, [fx, fy]] of k.corners(plan(x, y, w, d), 6).entries())
      box(`fastener-${i}`, fx - 1, fy - 1, 2, 2, h - 7, 0.6);
  }
  function ribs(name, x, y, w, count, z, module = 'base') {
    for (let i = 0; i < count; i++) box(`${name}-${i}`, x, y + i * 4, w, 1.5, z, 0.6, { module });
  }
  const effect = scene.build({ box, base, ribs, at, line, plan, P, k });
  const samples = Array.from({ length: 21 }, (_, i) => i / 20);
  A.settle(R, P, { states: samples });
  A.auditOrExit(R, P, { frames: samples, apart: true });
  const sorted = R.items.toSorted((a, b) => a.key - b.key);
  const origin = at([0, 0, 0]);
  const isForeground = (item) =>
    (id === 'mcp' && /^(rack-upright-1|rack-roof|roof-vent|monitor-)/.test(item.name)) ||
    (id === 'boards' && /^(platen|press-column|press-shoe|crosshead)/.test(item.name)) ||
    (id === 'graphql' && item.name.startsWith('reed-'));
  const markup = (i) =>
    `<g data-item="${i.name}" data-module="${i.module}"${i.field >= 0 ? ` data-field="${i.field}"` : ''}>${i.svg}</g>`;
  const art = {
    width,
    height,
    camera: glCamera(P),
    parts: R.solids.length,
    kind: id,
    effect,
    back: sorted
      .filter((i) => !isForeground(i))
      .map(markup)
      .join(''),
    front: sorted.filter(isForeground).map(markup).join(''),
    items: sorted.map((i) => ({
      name: i.name,
      key: i.key,
      lift: i.move.reduce((s, v, j) => s + v * R.V[j], 0),
      delta: at(i.move).map((v, j) => v - origin[j]),
      driver: i.driver,
      moving: i.move.some(Boolean),
    })),
  };
  writeFileSync(
    `src/preview/instruments/${id}.generated.ts`,
    `// Generated by scripts/build-instruments.mjs.\nexport default ${JSON.stringify(art)} as const;\n`,
  );
  writeFileSync(
    `docs/${id}-instrument-parts.json`,
    JSON.stringify(
      R.solids.map(({ name, kind }) => ({ name, kind })),
      null,
      2,
    ) + '\n',
  );
  console.log(`${id}: ${R.solids.length} solids, ${samples.length} audited mechanism positions.`);
}
